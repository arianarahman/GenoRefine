def md5_of_list(items: List[str]) -> str:
    h = hashlib.md5()
    for s in items:
        h.update(s.encode("utf-8"))
        h.update(b"\n")
    return h.hexdigest()


def md5_no_trailing_newline(items: List[str]) -> str:
    """MD5 helper matching the R scripts: join genes with LF and no trailing newline."""
    payload = "\n".join(map(str, items)).encode("utf-8")
    return hashlib.md5(payload).hexdigest()


def safe_pkg_version(pkg_name: str, module_name: Optional[str] = None) -> str:
    """Return installed package version for reproducibility logging."""
    try:
        from importlib import metadata as importlib_metadata
        return importlib_metadata.version(pkg_name)
    except Exception:
        try:
            if module_name is None:
                module_name = pkg_name
            mod = __import__(module_name)
            return str(getattr(mod, "__version__", "unknown"))
        except Exception:
            return "unavailable"


