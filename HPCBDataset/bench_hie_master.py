def log_preprocess_fingerprint(adata: ad.AnnData, tag: str = "BASE") -> None:
    var_names = [str(v) for v in adata.var_names.tolist()]
    obs_names = [str(o) for o in adata.obs_names.tolist()]
    msg = [
        f"[{tag}] n_obs={adata.n_obs}, n_vars={adata.n_vars}",
        f"[{tag}] var_md5={md5_of_list(var_names)}",
        f"[{tag}] obs_md5={md5_of_list(obs_names)}",
    ]
    if "X_pca" in adata.obsm:
        Xp = np.asarray(adata.obsm["X_pca"])
        msg.append(f"[{tag}] X_pca shape={Xp.shape}, var(PC1)={float(np.var(Xp[:, 0])):.6f}")
    if "canonical_hvg_md5" in adata.uns:
        msg.append(f"[{tag}] canonical_hvg_md5={adata.uns['canonical_hvg_md5']}")
    if "canonical_hvg_file" in adata.uns:
        msg.append(f"[{tag}] canonical_hvg_file={adata.uns['canonical_hvg_file']}")
    logging.info("\n".join(msg))


def compute_lisi_python(X: np.ndarray, labels: np.ndarray, k: int = 90) -> float:
    X = np.asarray(X)
    labels = np.asarray(labels)
    n = X.shape[0]
    k = min(int(k), n - 1) if n > 1 else 1

    nn = NearestNeighbors(n_neighbors=k)
    nn.fit(X)
    _, idx = nn.kneighbors(X)

    uniq, enc = np.unique(labels, return_inverse=True)
    n_classes = len(uniq)

    lisi_scores: List[float] = []
    for i in range(n):
        neigh = enc[idx[i]]
        counts = np.bincount(neigh, minlength=n_classes)
        probs = counts / k
        simpson = float(np.sum(probs**2))
        lisi = 1.0 / simpson if simpson > 0 else 1.0
        lisi_scores.append(lisi)

    return float(np.mean(lisi_scores))



def _rep_for_neighbors(adata: ad.AnnData, rep_key: str, n_dims: int) -> str:
    """Return an obsm key safe for neighbors (slice to n_dims if needed)."""
    if rep_key not in adata.obsm:
        raise KeyError(f"Missing embedding '{rep_key}' in adata.obsm")
    X = np.asarray(adata.obsm[rep_key])
    if not np.isfinite(X).all():
        raise ValueError(f"Non-finite values found in embedding '{rep_key}'")
    if n_dims is None or int(n_dims) <= 0 or X.shape[1] <= int(n_dims):
        return rep_key
    key2 = f"{rep_key}__nd{int(n_dims)}"
    if key2 not in adata.obsm or adata.obsm[key2].shape[0] != X.shape[0]:
        adata.obsm[key2] = X[:, : int(n_dims)].copy()
    return key2


def _select_hvgs_per_batch_union(
    adata: ad.AnnData,
    batch_key: str,
    n_top: int,
    flavor: str,
    layer: Optional[str],
    mode: str = "union",
) -> List[str]:
    """Compute HVGs per batch and return union/intersection gene list."""

    def _matrix_from_layer(aobj: ad.AnnData, lyr: Optional[str]):
        return aobj.layers[lyr] if lyr is not None and lyr in aobj.layers else aobj.X

    def _nonzero_gene_mask(aobj: ad.AnnData, lyr: Optional[str]) -> np.ndarray:
        X = _matrix_from_layer(aobj, lyr)
        sums = np.asarray(X.sum(axis=0)).ravel()
        return sums > 0

    def _run_hvg_safe(aobj: ad.AnnData, n_top_local: int, flavor_local: str, lyr: Optional[str], context: str):
        try:
            sc.pp.highly_variable_genes(
                aobj,
                n_top_genes=int(n_top_local),
                flavor=str(flavor_local),
                subset=False,
                layer=lyr,
            )
            return str(flavor_local)
        except ValueError as e:
            msg = str(e)
            if "Bin edges must be unique" not in msg:
                raise
            fallback = "seurat" if str(flavor_local) != "seurat" else "cell_ranger"
            logging.warning(
                "HVG bin-edge issue in %s with flavor=%s; retrying with flavor=%s after removing all-zero genes.",
                context, flavor_local, fallback,
            )
            keep = _nonzero_gene_mask(aobj, lyr)
            if keep.sum() == 0:
                raise ValueError(f"All genes are zero in {context}; cannot compute HVGs.") from e
            trimmed = aobj[:, keep].copy()
            sc.pp.highly_variable_genes(
                trimmed,
                n_top_genes=min(int(n_top_local), trimmed.n_vars),
                flavor=fallback,
                subset=False,
                layer=lyr,
            )
            hv = np.zeros(aobj.n_vars, dtype=bool)
            hv_idx = np.where(keep)[0][trimmed.var["highly_variable"].to_numpy()]
            hv[hv_idx] = True
            aobj.var["highly_variable"] = hv
            return fallback

    if batch_key not in adata.obs:
        raise KeyError(f"Missing batch_key '{batch_key}' in adata.obs")

    batches = adata.obs[batch_key].astype(str)
    all_hvgs: List[set] = []

    for b in sorted(pd.unique(batches)):
        sub = adata[batches == b].copy()
        used_flavor = _run_hvg_safe(sub, int(n_top), str(flavor), layer, context=f"batch={b}")
        hv = sub.var_names[sub.var["highly_variable"].to_numpy()].tolist()
        if len(hv) == 0:
            logging.warning("No HVGs selected for batch=%s using flavor=%s", b, used_flavor)
        all_hvgs.append(set(hv))

    if len(all_hvgs) == 0:
        raise ValueError("No batches available for HVG selection.")

    mode = str(mode).lower()
    if mode == "intersection":
        genes = set.intersection(*all_hvgs)
    else:
        genes = set.union(*all_hvgs)

    genes = [g for g in adata.var_names if g in genes]
    if len(genes) == 0:
        raise ValueError(f"No HVGs remained after per-batch {mode}.")
    return genes



def _read_canonical_hvg_file(txt_path: str) -> List[str]:
    if not os.path.exists(txt_path):
        raise FileNotFoundError(txt_path)

    ser = pd.read_csv(txt_path, header=None).iloc[:, 0].astype(str)
    hvgs: List[str] = []
    seen = set()
    for x in ser.tolist():
        g = str(x).strip()
        if g == "" or g.lower() == "nan":
            continue
        if g not in seen:
            hvgs.append(g)
            seen.add(g)
    if len(hvgs) == 0:
        raise ValueError(f"Canonical HVG file is empty: {txt_path}")
    return hvgs


def _subset_with_frozen_canonical_hvgs(adata: ad.AnnData, cfg: HieConfig) -> ad.AnnData:
    txt_path = os.path.join(cfg.out_folder, cfg.canonical_hvg_file)
    requested_hvgs = _read_canonical_hvg_file(txt_path)

    present = set(adata.var_names.astype(str).tolist())
    matched_hvgs = [g for g in requested_hvgs if g in present]
    missing_count = int(len(requested_hvgs) - len(matched_hvgs))

    if len(matched_hvgs) == 0:
        raise ValueError(f"No canonical HVGs from file matched adata.var_names. File={txt_path}")

    if cfg.require_exact_canonical_hvg_match and len(matched_hvgs) != len(requested_hvgs):
        raise ValueError(
            f"Canonical HVG file match is incomplete. File={txt_path} | "
            f"requested={len(requested_hvgs)} matched={len(matched_hvgs)} missing={missing_count}"
        )

    canonical_md5_master = md5_of_list(matched_hvgs)
    canonical_md5_r_style = md5_no_trailing_newline(matched_hvgs)
    logging.info(
        "Using frozen canonical HVG file: %s | requested=%d matched=%d missing=%d md5_master=%s md5_r_style=%s",
        txt_path,
        len(requested_hvgs),
        len(matched_hvgs),
        missing_count,
        canonical_md5_master,
        canonical_md5_r_style,
    )

    md5_path = os.path.join(cfg.out_folder, cfg.canonical_hvg_md5_file)
    if cfg.check_canonical_hvg_md5_file and os.path.exists(md5_path):
        try:
            expected_md5 = open(md5_path, "r", encoding="utf-8").read().strip().splitlines()[0].strip()
            if expected_md5 and expected_md5 not in (canonical_md5_r_style, canonical_md5_master):
                raise ValueError(
                    f"Canonical HIE HVG MD5 mismatch. File={txt_path} md5_file={md5_path} "
                    f"expected={expected_md5} observed_r_style={canonical_md5_r_style} observed_master={canonical_md5_master}"
                )
            logging.info("Canonical HIE HVG MD5 verified: %s", expected_md5)
        except IndexError:
            logging.warning("Canonical HIE HVG MD5 file exists but is empty: %s", md5_path)
    elif cfg.check_canonical_hvg_md5_file:
        logging.warning("Canonical HIE HVG MD5 file not found: %s", md5_path)

    meta_path = os.path.join(cfg.out_folder, cfg.canonical_hvg_metadata_file)
    if os.path.exists(meta_path):
        logging.info("Canonical HIE HVG metadata file found: %s", meta_path)

    out = adata[:, matched_hvgs].copy()
    out.uns["canonical_hvg_file"] = txt_path
    out.uns["canonical_hvg_md5"] = canonical_md5_master
    out.uns["canonical_hvg_md5_r_style"] = canonical_md5_r_style
    out.uns["canonical_hvg_n_genes"] = int(len(matched_hvgs))
    return out

def _normalize_obs_name(s: str) -> str:
    s = str(s)
    s = re.sub(r"-1$", "", s)
    s = re.sub(r"\.1$", "", s)
    s = s.replace(".", "-")
    return s


def infer_key_from_obs(adata: ad.AnnData, candidates: Tuple[str, ...]) -> Optional[str]:
    for k in candidates:
        if k in adata.obs.columns:
            return k
    return None


def _nan_guard(X: np.ndarray, name: str) -> np.ndarray:
    X = np.asarray(X)
    if not np.isfinite(X).all():
        logging.warning(f"{name}: NaN/Inf found; replacing with 0.")
        X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)
    return X


def sanitize_method_name(name: str) -> str:
    s = name.replace(" ", "_")
    s = s.replace("(", "_").replace(")", "")
    s = s.replace("/", "_").replace("__", "_")
    return s


